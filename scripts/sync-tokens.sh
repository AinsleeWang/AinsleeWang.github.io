#!/usr/bin/env bash
# sync-tokens.sh [ref]
#
# Pulls design tokens, article styles (if present), and logo assets from the
# wit-et-design-system repo at a given git ref (default: master) into this
# site. Idempotent: running it twice in a row with the same ref produces no
# further changes.
#
# Usage: scripts/sync-tokens.sh [ref]

set -euo pipefail

REF="${1:-master}"
SITE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DS_REPO="$SITE_ROOT/../wit-et-design-system"

if [ ! -d "$DS_REPO/.git" ]; then
  echo "error: design system repo not found at $DS_REPO" >&2
  exit 1
fi

COMMIT_HASH="$(git -C "$DS_REPO" rev-parse "$REF")"

VENDOR_DIR="$SITE_ROOT/src/styles/vendor"
PUBLIC_DIR="$SITE_ROOT/public"
mkdir -p "$VENDOR_DIR" "$PUBLIC_DIR"

write_vendor_css() {
  local src_path="$1"
  local dest_path="$2"

  if ! git -C "$DS_REPO" show "${REF}:${src_path}" > /tmp/sync-tokens-src.css 2>/dev/null; then
    echo "notice: ${src_path} not found at ${REF}, skipping ${dest_path}"
    return 0
  fi

  {
    echo "/* AUTO-GENERATED by scripts/sync-tokens.sh — do not edit by hand. */"
    echo "/* Source: wit-et-design-system ${src_path} @ ${REF} (${COMMIT_HASH}) */"
    echo
    cat /tmp/sync-tokens-src.css
  } > "$dest_path"
  rm -f /tmp/sync-tokens-src.css
}

write_vendor_css "tokens/tokens.css" "$VENDOR_DIR/tokens.css"
write_vendor_css "article.css" "$VENDOR_DIR/article.css"

copy_asset() {
  local src_path="$1"
  local dest_path="$2"

  if ! git -C "$DS_REPO" show "${REF}:${src_path}" > "$dest_path" 2>/dev/null; then
    echo "notice: ${src_path} not found at ${REF}, skipping ${dest_path}"
    rm -f "$dest_path"
    return 0
  fi
}

copy_asset "assets/logo/favicon.svg" "$PUBLIC_DIR/favicon.svg"
copy_asset "assets/logo/symbol.svg" "$PUBLIC_DIR/symbol.svg"

echo "sync-tokens: synced from ${REF} (${COMMIT_HASH})"
